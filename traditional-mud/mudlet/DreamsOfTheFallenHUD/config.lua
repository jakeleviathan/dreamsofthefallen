# Dreams of the Fallen Official HUD

A maximalist gothic-fantasy Mudlet interface for **Dreams of the Fallen**.

Features:
- ornate top vitals shrine
- red Health, blue Mana, and green Movement gauges
- dedicated gothic target panel with target name and health
- clean, readable combat text
- live GMCP updates from `Dreams.Vitals`, `Dreams.Target`, and `Char.Status`

The HUD is designed to be offered automatically by the Dreams of the Fallen server through Mudlet's `Client.GUI` GMCP extension.
